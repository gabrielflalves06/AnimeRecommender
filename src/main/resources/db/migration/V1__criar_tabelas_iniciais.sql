CREATE TABLE anime (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_externo       BIGINT       NOT NULL UNIQUE,
    titulo           VARCHAR(255) NOT NULL,
    imagem           VARCHAR(500),
    data_lancamento  DATE,
    nota             INTEGER,
    popularidade     INTEGER,
    sinopse          TEXT,
    tipo             VARCHAR(30)
);

CREATE TABLE genero (
    id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome  VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE tema (
    id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome  VARCHAR(150) NOT NULL UNIQUE
);

CREATE TABLE demografia (
    id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome  VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE anime_genero (
    anime_id   BIGINT NOT NULL REFERENCES anime (id) ON DELETE CASCADE,
    genero_id  BIGINT NOT NULL REFERENCES genero (id),
    PRIMARY KEY (anime_id, genero_id)
);

CREATE TABLE anime_tema (
    anime_id  BIGINT NOT NULL REFERENCES anime (id) ON DELETE CASCADE,
    tema_id   BIGINT NOT NULL REFERENCES tema (id),
    PRIMARY KEY (anime_id, tema_id)
);

CREATE TABLE anime_demografia (
    anime_id       BIGINT NOT NULL REFERENCES anime (id) ON DELETE CASCADE,
    demografia_id  BIGINT NOT NULL REFERENCES demografia (id),
    PRIMARY KEY (anime_id, demografia_id)
);

CREATE INDEX idx_anime_genero_genero ON anime_genero (genero_id);
CREATE INDEX idx_anime_tema_tema ON anime_tema (tema_id);
CREATE INDEX idx_anime_demografia_demografia ON anime_demografia (demografia_id);